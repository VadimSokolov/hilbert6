def check_ridge_and_diffusion(curve):
    """Two checks that explain the shape of the posterior (curve: the linearized analysis of the whole data set, from fisher_curves).
    (a) How much the reaction term matters in each window: the largest and the root mean square difference, over the data points,
        between the solution at the truth and the solution with r = 0 (pure diffusion), in units of the noise sd.
    (b) The ridge of the long windows is the set of parameters that give the same front trajectory: the Fisher information of the
        half height position x_f(t_j) alone (j <= nt; the noise level does not change the orientation) is compared with that of the
        whole data set."""
    D, r = TRUTH
    two = solve([D, D], [r, 0.0], TOBS, SENS)
    for T in WINDOWS:
        nt = int(round(T / DTOBS))
        d = (two[0, :nt] - two[1, :nt]) / DELTA
        log("CHECK diffusion: window T=%g: the reaction term changes the solution at the truth by at most %.1f and by %.2f rms noise sd over the data points" %
            (T, np.abs(d).max(), np.sqrt(np.mean(d ** 2))))
    eps = 1e-3
    n, x = node_grid(LX, H)
    pts = [(D, r), (D * np.exp(eps), r), (D * np.exp(-eps), r), (D, r * np.exp(eps)), (D, r * np.exp(-eps))]
    prof = solve([p[0] for p in pts], [p[1] for p in pts], TOBS, x)
    pos = np.array([[front_position(prof[k, j], x) for j in range(len(TOBS))] for k in range(5)])
    JD, Jr = (pos[1] - pos[2]) / (2 * eps), (pos[3] - pos[4]) / (2 * eps)
    for T in WINDOWS[1:]:
        nt = int(round(T / DTOBS))
        A = np.array([[np.sum(JD[:nt] ** 2), np.sum(JD[:nt] * Jr[:nt])], [np.sum(JD[:nt] * Jr[:nt]), np.sum(Jr[:nt] ** 2)]])
        s = axes_summary(np.linalg.inv(A))
        w = next(c for c in curve if abs(c["T"] - T) < 1e-9)
        log("CHECK front trajectory: window T=%g: Fisher information of the half height position alone: major axis %.1f deg, corr %.4f, "
            "axis ratio %.1f, corr(a,b) %+.3f; whole data set: major axis %.1f deg, corr %.4f, axis ratio %.1f, corr(a,b) %+.3f" %
            (T, s["angle"], s["corr"], s["ratio"], s["corr_ab"], w["angle"], w["corr"], w["ratio"], w["corr_ab"]))


# ==================== calibration over noise draws
def calibration(post, clean, nrep, quick=False):
    """Repeat the experiment with other noise draws (same truth, same design).  For every window the exact posterior of every draw
    is evaluated on one grid shared by all draws (centered at the truth, axes along the principal axes of the linearized posterior),
    so that the forward model is solved once per grid node.  Reported: how often the truth lies inside the 50 and 90 percent
    highest posterior density regions, and the mean posterior mass of the smallest such region that contains the truth."""
    rng = np.random.default_rng(SEED_CAL)
    ytab = clean[None].reshape(1, -1) + DELTA * rng.standard_normal((nrep, clean.size))
    tl = np.log(TRUTH)
    out = {}
    for T in WINDOWS:
        nt = int(round(T / DTOBS))
        g0, J = post.jac(tl, nt)
        Jd = J / DELTA
        Cl = np.linalg.inv(Jd.T @ Jd + np.diag(1 / PSD ** 2))
        ev, evec = np.linalg.eigh(Cl)
        K, n = (12.0, 61 if quick else 101) if T == WINDOWS[0] else (9.0, 61 if quick else 91)
        p = np.linspace(-K, K, n) * np.sqrt(ev[1]); q = np.linspace(-K, K, n) * np.sqrt(ev[0])
        P, Q = np.meshgrid(p, q, indexing="ij")
        th = tl[None, :] + P.reshape(-1, 1) * evec[:, 1][None, :] + Q.reshape(-1, 1) * evec[:, 0][None, :]
        Gm = post.G(th, nt).reshape(len(th), -1)
        yt = ytab[:, :nt * len(SENS)]
        S = (yt ** 2).sum(1)[None, :] - 2.0 * Gm @ yt.T + (Gm ** 2).sum(1)[:, None]          # |y - G|^2 for every node and draw
        lp = -0.5 * S / DELTA ** 2 - 0.5 * np.sum(((th - PM) / PSD) ** 2, axis=1)[:, None]
        lp -= lp.max(axis=0, keepdims=True)
        w = np.exp(lp)
        c = (n // 2) * n + n // 2                                                              # the node at the truth
        level = np.array([w[lp[:, i] >= lp[c, i], i].sum() / w[:, i].sum() for i in range(nrep)])
        edge = np.zeros((n, n), bool); edge[0, :] = edge[-1, :] = edge[:, 0] = edge[:, -1] = True
        em = (w[edge.ravel()] / w.sum(0)[None, :]).sum(0).max()
        out[T] = dict(cov50=float(np.mean(level <= 0.5)), cov90=float(np.mean(level <= 0.9)), mean_level=float(level.mean()), edge=float(em), nrep=nrep)
        log("CALIBRATION window T=%g: %d noise draws, truth inside the 50%% and 90%% HPD regions in %.1f%% and %.1f%% of them (standard error of the "
            "second %.1f%%); mean HPD level of the truth %.3f (0.5 for a calibrated posterior); posterior mass on the grid edge at most %.1e" %
            (T, nrep, 100 * out[T]["cov50"], 100 * out[T]["cov90"], 100 * np.sqrt(0.09 / nrep), out[T]["mean_level"], em))
    return out


# ==================== generator (conditional quantile maps)
def hpd_log_threshold(g, mass):
    o = np.argsort(g["w"])[::-1]
    k = int(np.searchsorted(np.cumsum(g["w"][o]), mass))
    return g["lpost"][o][k]


def log_density_at(g, th):
    d = th - g["gcenter"]
    pq = np.stack([d @ g["evec"][:, 1], d @ g["evec"][:, 0]], axis=1)
    n = g["n"]
    return RegularGridInterpolator((g["p"], g["q"]), g["lpost"].reshape(n, n), bounds_error=False, fill_value=-np.inf)(pq)


def compare_to_exact(g, samp):
    """Differences between generator draws and the exact grid posterior, in units of the exact posterior sd."""
    m, C = moments(g["w"], g["th"])
    sd = np.sqrt(np.diag(C))
    ev, evec = np.linalg.eigh(C)
    ms, Cs = samp.mean(axis=0), np.cov(samp.T)
    pa = (samp - m) @ evec
    lp = log_density_at(g, samp)
    return dict(dmean=(ms - m) / sd, sdratio=np.sqrt(np.diag(Cs)) / sd, corr=Cs[0, 1] / np.sqrt(Cs[0, 0] * Cs[1, 1]),
                corr_exact=C[0, 1] / sd[0] / sd[1], dmean_pa=pa.mean(axis=0) / np.sqrt(ev), sdratio_pa=pa.std(axis=0) / np.sqrt(ev),
                in50=float(np.mean(lp >= hpd_log_threshold(g, 0.5))), in90=float(np.mean(lp >= hpd_log_threshold(g, 0.9))))


def generator_study(post, res, T, M, quick):
    """A small conditional generator for (log D, log r) given the data, trained on M simulated pairs by the check loss.
    Summary statistic: the gradient of the data misfit J^T (y - G(pilot)) / delta^2 at a pilot estimate (the posterior mode; one
    adjoint solve gives it in a partial differential equation problem).  The generator is a triangular map of conditional quantile
    functions: log D = Q1(s, z1), log r = Q2(s, log D, z2) with z1, z2 independent standard normal (U uniform: z = Phi^{-1}(U)).
    Each Q is a linear skip connection plus a two layer network with 64 units.  Two sets of simulations: (i) log D, log r uniform on
    a box of half width 4.5 posterior sds around the pilot (the prior is nearly flat there, and the prior density is used as an
    importance weight), (ii) draws from the prior."""
    import torch
    import torch.nn as nn
    from scipy.special import ndtri
    torch.set_num_threads(WORKERS)
    if T == 12.0:
        log("GENERATOR study: torch", torch.__version__, "with", WORKERS, "threads; training seeds", SEEDS_TRAIN, "; simulation seed", SEED_SIM)
    g = res[T]
    nt = g["nt"]
    thp, C = g["map"], g["laplace_C"]
    L = np.linalg.cholesky(C)
    g0, J = post.jac(thp, nt)
    g0f = g0.ravel()
    s_obs = (post.y[:nt].ravel() - g0f) @ J / DELTA ** 2

    def simulate(proposal, seed):
        rng = np.random.default_rng(seed)
        if proposal == "pilot":
            th = thp[None, :] + rng.uniform(-4.5, 4.5, size=(M, 2)) @ L.T
            logw = -0.5 * np.sum(((th - PM) / PSD) ** 2, axis=1)
        else:
            th = PM[None, :] + PSD[None, :] * rng.standard_normal((M, 2))
            logw = np.zeros(M)
        w = np.exp(logw - logw.max()); w *= M / w.sum()
        s = np.empty((M, 2))
        t0 = time.time()
        for i in range(0, M, 1500):
            gg = post.G(th[i:i + 1500], nt)
            yy = gg.reshape(len(gg), -1) + DELTA * rng.standard_normal((len(gg), gg[0].size))
            s[i:i + 1500] = (yy - g0f[None, :]) @ J / DELTA ** 2
        log("   GENERATOR window T=%g, %s proposal: %d simulated pairs in %.0f s; importance weights max/mean %.2f" %
            (T, proposal, M, time.time() - t0, w.max() / w.mean()))
        return th, w, s

    class QNet(nn.Module):
        def __init__(self, din, width=64):
            super().__init__()
            self.skip = nn.Linear(din, 1)
            self.mlp = nn.Sequential(nn.Linear(din, width), nn.SiLU(), nn.Linear(width, width), nn.SiLU(), nn.Linear(width, 1))

        def forward(self, x):
            return (self.skip(x) + self.mlp(x)).squeeze(-1)

    def train(th, w, s, epochs, seed, batch=512):
        torch.manual_seed(seed)
        m = len(th)
        z = np.linalg.solve(L, (th - thp[None, :]).T).T
        zs = z.std(axis=0); z = z / zs
        sm, ss = s.mean(axis=0), s.std(axis=0)
        S = torch.tensor((s - sm) / ss, dtype=torch.float32)
        so = torch.tensor((s_obs - sm) / ss, dtype=torch.float32)
        Z = torch.tensor(z, dtype=torch.float32)
        W = torch.tensor(w, dtype=torch.float32)
        q1, q2 = QNet(3), QNet(4)
        opt = torch.optim.Adam(list(q1.parameters()) + list(q2.parameters()), lr=3e-3)
        sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=epochs, eta_min=1e-4)
        nrm = lambda u: torch.tensor(ndtri(u.numpy().clip(1e-6, 1 - 1e-6)), dtype=torch.float32)
        for _ in range(epochs):
            perm = torch.randperm(m)
            for i in range(0, m, batch):
                ix = perm[i:i + batch]
                t1, t2 = torch.rand(len(ix)), torch.rand(len(ix))
                r1 = Z[ix, 0] - q1(torch.cat([S[ix], nrm(t1)[:, None]], 1))
                r2 = Z[ix, 1] - q2(torch.cat([S[ix], Z[ix, 0:1], nrm(t2)[:, None]], 1))
                loss = (W[ix] * (torch.maximum(t1 * r1, (t1 - 1) * r1) + torch.maximum(t2 * r2, (t2 - 1) * r2))).mean()
                opt.zero_grad(); loss.backward(); opt.step()
            sched.step()

        def sample(n, seed2=1):
            gen = torch.Generator().manual_seed(seed2)
            z1, z2 = torch.randn(n, generator=gen), torch.randn(n, generator=gen)
            sob = so[None, :].repeat(n, 1)
            with torch.no_grad():
                a = q1(torch.cat([sob, z1[:, None]], 1))
                b = q2(torch.cat([sob, a[:, None], z2[:, None]], 1))
            return thp[None, :] + (torch.stack([a, b], 1).numpy().astype(float) * zs) @ L.T
        return sample

    out = dict(T=T, M=M)
    nm = 4000 if quick else 20000
    th, w, s = simulate("pilot", SEED_SIM)
    runs = {}
    for Msub in (1000, 4000, M):
        for seed in SEEDS_TRAIN:
            samp = train(th[:Msub], w[:Msub], s[:Msub], 300 if Msub < 10000 else 150, seed)(20000)
            c = compare_to_exact(g, samp)
            runs[(Msub, seed)] = c
            log("   GENERATOR window T=%g, pilot proposal, M=%d, training seed %d: mean difference in exact sd (log D, log r) (%+.3f, %+.3f); "
                "sd ratio (%.3f, %.3f); corr %.4f (exact %.4f); along the principal axes sd ratio (%.3f minor, %.3f major); "
                "inside the exact 50%% and 90%% regions: %.3f, %.3f" %
                (T, Msub, seed, *c["dmean"], *c["sdratio"], c["corr"], c["corr_exact"], *c["sdratio_pa"], c["in50"], c["in90"]))
            if Msub == M and seed == SEEDS_TRAIN[0]:
                out["samples"] = samp[:2000]
    out["pilot_runs"] = runs
    th, w, s = simulate("prior", SEED_SIM + 1)
    samp = train(th, w, s, 150, SEEDS_TRAIN[0])(20000)
    c = compare_to_exact(g, samp)
    out["prior_run"] = c
    log("   GENERATOR window T=%g, prior proposal, M=%d: mean difference in exact sd (log D, log r) (%+.2f, %+.2f); sd ratio (%.1f, %.1f); "
        "inside the exact 50%% and 90%% regions: %.3f, %.3f" % (T, M, *c["dmean"], *c["sdratio"], c["in50"], c["in90"]))
    return out


