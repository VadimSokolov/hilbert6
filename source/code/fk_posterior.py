# ==================== forward model
def node_grid(lx, h):
    n = int(round(lx / h)) + 1
    return n, np.linspace(0.0, lx, n)


def u0(x):
    return 0.5 * erfc((x - X0) / (np.sqrt(2.0) * S0))


def solve(D, r, obs_t, xs, lx=LX, h=H, dt=DT, track=False):
    """Pseudospectral method of lines (cosine transform of type I, Neumann ends) with Strang splitting.
    The diffusion step is exact on the cosine modes, the reaction step is the exact flow of the logistic equation.
    D, r: arrays of length B.  Returns u at the sensors xs (grid nodes) at times obs_t: shape (B, len(obs_t), len(xs))."""
    D = np.asarray(D, float).ravel(); r = np.asarray(r, float).ravel()
    n, x = node_grid(lx, h)
    idx = np.rint(np.asarray(xs) / (lx / (n - 1))).astype(int)
    assert np.allclose(idx * (lx / (n - 1)), xs), "sensors must be grid nodes"
    nsteps = int(round(float(np.max(obs_t)) / dt))
    obs_step = {int(round(t / dt)): j for j, t in enumerate(obs_t)}
    assert all(abs(k * dt - obs_t[j]) < 1e-9 for k, j in obs_step.items()), "observation times must be multiples of dt"
    lam = (np.pi * np.arange(n) / lx) ** 2
    E = np.exp(-np.outer(D, lam) * dt)
    g, gh, gmh = (np.exp(c * r * dt)[:, None] for c in (1.0, 0.5, -0.5))
    V = np.tile(u0(x), (D.size, 1))
    V = gh * V / (1.0 + (gh - 1.0) * V)            # V = R(dt/2) U;  V_{n+1} = R(dt) Dif(dt) V_n;  U_n = R(-dt/2) V_n
    out = np.empty((D.size, len(obs_t), len(idx)))
    clipped = 0.0
    for k in range(1, nsteps + 1):
        C = dct(V, type=1, axis=1, workers=WORKERS)
        C *= E
        V = idct(C, type=1, axis=1, workers=WORKERS)
        if track:
            clipped = max(clipped, float(-V.min()), float(V.max() - 1.0))
        np.clip(V, 0.0, 1.0, out=V)                # near the posterior only roundoff (1e-16) is clipped (see check_solver)
        V = g * V / (1.0 + (g - 1.0) * V)
        if k in obs_step:
            out[:, obs_step[k], :] = (gmh * V / (1.0 + (gmh - 1.0) * V))[:, idx]
    return (out, clipped) if track else out


def solve_profile(D, r, t, lx=LX, h=H, dt=DT):
    """The whole profile u(t, .) on the grid, for one parameter pair (for plots and for the front speed)."""
    n, x = node_grid(lx, h)
    return x, solve([D], [r], [t], x, lx, h, dt)[0, 0]


def reference(D, r, obs_t, xs, lx=LX):
    """Independent solver: second order centered differences with mirror ghost nodes at both ends, variable order BDF
    in time (rtol 1e-10), at the spacings 0.025 and 0.0125, combined by Richardson extrapolation (error O(h^4))."""
    res = {}
    for hf in (0.025, 0.0125):
        n, x = node_grid(lx, hf)
        idx = np.rint(np.asarray(xs) / (lx / (n - 1))).astype(int)
        main = -2.0 * np.ones(n); up = np.ones(n - 1); lo = np.ones(n - 1); up[0] = 2.0; lo[-1] = 2.0
        lap = sp.diags([lo, main, up], [-1, 0, 1], format="csc") / hf ** 2
        sol = solve_ivp(lambda t, u: D * (lap @ u) + r * u * (1.0 - u), (0.0, float(np.max(obs_t))), u0(x),
                        method="BDF", jac=lambda t, u: D * lap + sp.diags(r * (1.0 - 2.0 * u), 0, format="csc"),
                        t_eval=np.asarray(obs_t), rtol=1e-10, atol=1e-12)
        assert sol.success
        res[hf] = sol.y[idx, :].T
    return (4.0 * res[0.0125] - res[0.025]) / 3.0, res


# ==================== checks of the forward model
def check_solver():
    log("CHECK solver: production solver (h=%.3g, dt=%.4g) against (a) the same method with h/2 and dt/2, "
        "(b) the independent finite difference BDF reference; max |difference| over the 72 x 48 data grid" % (H, DT))
    for D, r in [(1.0, 1.0), (1.2, 0.9), (0.8, 1.1), (0.5, 0.7), (1.5, 1.5), (0.5, 2.0), (2.0, 0.5)]:
        a = solve([D], [r], TOBS, SENS)[0]
        b = solve([D], [r], TOBS, SENS, h=H / 2, dt=DT / 2)[0]
        c, _ = reference(D, r, TOBS, SENS)
        clip = solve([D], [r], TOBS, SENS, track=True)[1]
        log("   D=%.2f r=%.2f   vs refined %.2e   vs reference %.2e   largest value clipped to [0, 1]: %.1e   (noise sd %.2f)" %
            (D, r, np.abs(a - b).max(), np.abs(a - c).max(), clip, DELTA))


def front_position(u, x):
    k = int(np.argmax(u < 0.5))
    return x[k - 1] + (u[k - 1] - 0.5) / (u[k - 1] - u[k]) * (x[k] - x[k - 1])


def truth_front():
    """Position of the half height point of the true solution at the window ends, and its mean speed over the second half."""
    n, x = node_grid(LX, H)
    ts = [0.25, 0.5, 1.5, 3.0, 6.0, 12.0]
    prof = solve([TRUTH[0]], [TRUTH[1]], ts, x)[0]
    pos = {0.0: front_position(u0(x), x)}
    pos.update({t: front_position(prof[j], x) for j, t in enumerate(ts)})
    cs = 2.0 * np.sqrt(TRUTH[0] * TRUTH[1])
    log("TRUTH front: half height position minus X0, in units of sqrt(D*/r*): " + ", ".join("t=%g: %.3f" % (t, pos[t] - X0) for t in sorted(pos)))
    for T in WINDOWS:
        t0 = {0.5: 0.25, 3.0: 1.5, 12.0: 6.0}[T]
        log("   window T=%g: mean speed of the half height point over [%g, %g] = %.3f c*; displacement %.2f widths; front width (10 to 90 percent) at T: %.2f widths" %
            (T, t0, T, (pos[T] - pos[t0]) / (T - t0) / cs, pos[T] - X0,
             np.interp(0.1, prof[ts.index(T)][::-1], x[::-1]) - np.interp(0.9, prof[ts.index(T)][::-1], x[::-1])))
    return pos


def check_front_speed():
    """Speed of the half height point against 2 sqrt(rD) and the asymptotics c* (1 - 3/(4 r t)) of Bramson."""
    log("CHECK front speed: speed of the half height point (centered difference over +-2/r), divided by c* = 2 sqrt(rD), "
        "against the asymptotic formula 1 - 3/(4 r t)")
    out = []
    for D, r in [(1.0, 1.0), (0.5, 2.0), (2.0, 0.5)]:
        cs = 2.0 * np.sqrt(r * D)
        tmax = 26.0 / r                       # beyond r t = 30 roundoff at 1e-16 seeds a spurious front ahead of the real one
        lx = X0 + cs * tmax + 40.0
        step = 0.25 / r                       # observation spacing in units of 1/r
        times = step * np.arange(1, int(round(tmax / step)) + 1)
        n, x = node_grid(lx, H)
        res = solve([D], [r], times, x[1:-1], lx=lx, dt=step / 20.0)[0]
        pos = np.array([front_position(res[j], x[1:-1]) for j in range(len(times))])
        row = []
        for tau in (3.0, 6.0, 12.0, 20.0):
            j = int(round(tau / 0.25)) - 1
            k = int(round(2.0 / 0.25))
            row.append((tau, (pos[j + k] - pos[j - k]) / (times[j + k] - times[j - k]) / cs, 1.0 - 0.75 / tau))
        log("   D=%.1f r=%.1f c*=%.3f: " % (D, r, cs) + "  ".join("r t=%g: %.4f (formula %.4f)" % q for q in row))
        out.append(((D, r), row))
    return out


# ==================== data
def make_data():
    clean, refs = reference(TRUTH[0], TRUTH[1], TOBS, SENS)
    rng = np.random.default_rng(SEED_DATA)
    y = clean + DELTA * rng.standard_normal(clean.shape)
    log("DATA: noise draw with seed %d; rms of (y - clean) = %.4f; the two finite difference references (h=0.025, 0.0125) differ by at most %.1e" %
        (SEED_DATA, np.sqrt(np.mean((y - clean) ** 2)), np.abs(refs[0.025] - refs[0.0125]).max()))
    return clean, y


# ==================== posterior machinery
class Posterior:
    def __init__(self, y):
        self.y = y

    def G(self, theta, nt):
        th = np.atleast_2d(theta)
        out = []
        for i in range(0, len(th), 1500):          # chunks keep memory below 1 GB
            c = th[i:i + 1500]
            out.append(solve(np.exp(c[:, 0]), np.exp(c[:, 1]), TOBS[:nt], SENS))
        return np.concatenate(out)

    def logpost(self, theta, nt, solver=None):
        th = np.atleast_2d(theta)
        g = self.G(th, nt) if solver is None else solver(th, nt)
        ll = -0.5 * np.sum(((self.y[None, :nt, :] - g) / DELTA) ** 2, axis=(1, 2))
        lp = -0.5 * np.sum(((th - PM) / PSD) ** 2, axis=1)
        return ll + lp

    def jac(self, theta, nt, eps=1e-3):
        pts = np.array([theta, theta + [eps, 0], theta - [eps, 0], theta + [0, eps], theta - [0, eps]])
        g = self.G(pts, nt)
        return g[0], np.stack([((g[1] - g[2]) / (2 * eps)).ravel(), ((g[3] - g[4]) / (2 * eps)).ravel()], axis=1)

    def lm(self, theta, nt, iters=60):
        """Levenberg Marquardt for the maximum a posteriori point; returns it and the Laplace covariance."""
        lam = 1e-3
        f = -self.logpost(theta, nt)[0]
        for _ in range(iters):
            g0, J = self.jac(theta, nt)
            Jd = J / DELTA
            res = (self.y[:nt] - g0).ravel() / DELTA
            grad = -(Jd.T @ res) + (theta - PM) / PSD ** 2
            Hs = Jd.T @ Jd + np.diag(1 / PSD ** 2)
            moved = False
            while lam < 1e8:
                step = -np.linalg.solve(Hs + lam * np.diag(np.diag(Hs)), grad)
                fn = -self.logpost(theta + step, nt)[0]
                if fn < f:
                    theta, f, lam, moved = theta + step, fn, max(lam / 3, 1e-9), True
                    break
                lam *= 4
            if not moved or np.max(np.abs(step)) < 1e-9:
                break
        g0, J = self.jac(theta, nt)
        Hs = (J / DELTA).T @ (J / DELTA) + np.diag(1 / PSD ** 2)
        return theta, np.linalg.inv(Hs)


def moments(w, th):
    m = w @ th
    d = th - m
    return m, (d * w[:, None]).T @ d


def axes_summary(C):
    sd = np.sqrt(np.diag(C))
    ev, evec = np.linalg.eigh(C)
    major = evec[:, 1]
    ang = np.degrees(np.arctan2(major[1], major[0])) % 180.0
    va = (C[0, 0] + C[1, 1] + 2 * C[0, 1]) / 4.0           # a = (log D + log r)/2 = log(c*/2)... speed
    vb = (C[0, 0] + C[1, 1] - 2 * C[0, 1]) / 4.0           # b = (log D - log r)/2 = log sqrt(D/r): width
    cab = (C[0, 0] - C[1, 1]) / 4.0
    return dict(sd=sd, corr=C[0, 1] / sd[0] / sd[1], ratio=np.sqrt(ev[1] / ev[0]), angle=ang,
                sd_a=np.sqrt(va), sd_b=np.sqrt(vb), corr_ab=cab / np.sqrt(va * vb))


def weighted_quantile(v, w, qs):
    o = np.argsort(v)
    c = np.cumsum(w[o]) - 0.5 * w[o]
    return np.interp(qs, c / c[-1], v[o])


def grid_posterior(post, nt, center, C, K=6.5, n=61, max_pass=3, tol=2e-5, verbose=True):
    """Exact posterior of (log D, log r) on a regular grid in the principal axes of the current covariance estimate.
    The grid is rebuilt around the grid mean and covariance until the posterior mass on its edge is below tol."""
    for ps in range(max_pass):
        ev, evec = np.linalg.eigh(C)
        sd = np.sqrt(ev)
        gcenter = center
        p = np.linspace(-K, K, n) * sd[1]
        q = np.linspace(-K, K, n) * sd[0]
        P, Q = np.meshgrid(p, q, indexing="ij")
        th = center[None, :] + P.reshape(-1, 1) * evec[:, 1][None, :] + Q.reshape(-1, 1) * evec[:, 0][None, :]
        lpost = post.logpost(th, nt)
        w = np.exp(lpost - lpost.max()); w /= w.sum()
        m, C2 = moments(w, th)
        edge = np.zeros((n, n), bool); edge[0, :] = edge[-1, :] = edge[:, 0] = edge[:, -1] = True
        em = w[edge.ravel()].sum()
        if verbose:
            log("   grid pass %d: %d nodes, edge mass %.1e, mean (%.5f, %.5f), sd (%.5f, %.5f)" %
                (ps + 1, n * n, em, m[0], m[1], np.sqrt(C2[0, 0]), np.sqrt(C2[1, 1])))
        done = em < tol
        center, C = m, C2
        if done:
            break
    return dict(center=center, C=C, th=th, w=w, lpost=lpost, p=p, q=q, evec=evec, gcenter=gcenter, n=n, edge=em, K=K)


def hpd_threshold(w, mass):
    o = np.argsort(w)[::-1]
    c = np.cumsum(w[o])
    k = int(np.searchsorted(c, mass))
    return w[o][min(k, len(w) - 1)]


def hpd_level_of(g, point):
    """Posterior mass of the smallest highest posterior density region whose boundary passes through point."""
    d = np.asarray(point) - g["gcenter"]
    pq = np.array([d @ g["evec"][:, 1], d @ g["evec"][:, 0]])
    n = g["n"]
    interp = RegularGridInterpolator((g["p"], g["q"]), g["lpost"].reshape(n, n), bounds_error=False, fill_value=-np.inf)
    lp = float(interp(pq[None, :])[0])
    w = np.exp(g["lpost"] - g["lpost"].max())
    return float(w[g["lpost"] >= lp].sum() / w.sum())


def summarize(g, truth_log):
    m, C = g["center"], g["C"]
    s = axes_summary(C)
    w, th = g["w"], g["th"]
    s["mean_log"] = m
    s["mean"] = np.array([w @ np.exp(th[:, 0]), w @ np.exp(th[:, 1])])
    s["q90"] = [weighted_quantile(np.exp(th[:, j]), w, [0.05, 0.95]) for j in range(2)]
    s["hpd_truth"] = hpd_level_of(g, truth_log)
    dm = th - m
    s["skew"] = (w @ dm ** 3) / np.sqrt(w @ dm ** 2) ** 3      # skewness of log D and of log r
    s["maha_truth"] = float((truth_log - m) @ np.linalg.solve(C, truth_log - m))
    return s


def subgrid_check(g, nt, post):
    """Quadrature check: moments from every second node in each direction against the full grid."""
    n = g["n"]
    sel = np.zeros((n, n), bool); sel[::2, ::2] = True
    sel = sel.ravel()
    w = g["w"][sel]; w = w / w.sum()
    m, C = moments(w, g["th"][sel])
    sd = np.sqrt(np.diag(g["C"]))
    return np.max(np.abs(m - g["center"]) / sd), np.max(np.abs(np.sqrt(np.diag(C)) - sd) / sd)


# ==================== the three windows
def run_windows(post, quick=False):
    res = {}
    nt1 = int(round(WINDOWS[0] / DTOBS))
    gd = np.linspace(-2.5, 2.5, 21)
    GD, GR = np.meshgrid(PM[0] + gd * PSD[0], PM[1] + gd * PSD[1], indexing="ij")
    th0 = np.stack([GD.ravel(), GR.ravel()], axis=1)
    lp = post.logpost(th0, nt1)
    theta = th0[np.argmax(lp)]
    log("coarse scan of the prior box (21 x 21 nodes, window %g): best node D=%.3f r=%.3f" % (WINDOWS[0], *np.exp(theta)))
    for T in WINDOWS:
        nt = int(round(T / DTOBS))
        theta, C = post.lm(theta, nt)
        # safeguard: a coarse scan of the whole prior box must not beat the local optimum
        gs = np.linspace(-2.0, 2.0, 41)
        GD, GR = np.meshgrid(PM[0] + gs * PSD[0], PM[1] + gs * PSD[1], indexing="ij")
        ths = np.stack([GD.ravel(), GR.ravel()], axis=1)
        lps = post.logpost(ths, nt)
        lpm = post.logpost(theta, nt)[0]
        log("window T=%g: n_obs=%d  MAP D=%.4f r=%.4f  (log posterior %.3f; best of a 41 x 41 scan of the prior box %.3f)  "
            "Laplace sd(log D, log r)=(%.4f, %.4f)" % (T, nt * len(SENS), *np.exp(theta), lpm, lps.max(), *np.sqrt(np.diag(C))))
        assert lpm >= lps.max() - 1e-3, "local optimum is worse than the scan"
        K, n = (8.0, 61 if quick else 81) if T == WINDOWS[0] else (6.5, 41 if quick else 61)
        g = grid_posterior(post, nt, theta, C, K=K, n=n)
        g["map"], g["laplace_C"], g["nt"], g["T"] = theta, C, nt, T
        g["summary"] = summarize(g, np.log(TRUTH))
        g["sub_check"] = subgrid_check(g, nt, post)
        s = g["summary"]
        log("   EXACT window T=%g: mean D=%.4f r=%.4f; 90%% intervals D [%.4f, %.4f], r [%.4f, %.4f]; sd(log D)=%.5f sd(log r)=%.5f "
            "corr=%.4f; axis ratio %.2f, major axis %.1f deg; sd(a)=%.5f sd(b)=%.5f corr(a,b)=%.3f; truth in the %.1f%% HPD region "
            "(Mahalanobis^2 %.2f); Laplace sd (%.5f, %.5f) corr %.4f; skewness of (log D, log r) (%.2f, %.2f)" %
            (T, *s["mean"], *s["q90"][0], *s["q90"][1], *s["sd"], s["corr"], s["ratio"], s["angle"], s["sd_a"], s["sd_b"],
             s["corr_ab"], 100 * s["hpd_truth"], s["maha_truth"], *np.sqrt(np.diag(C)), C[0, 1] / np.sqrt(C[0, 0] * C[1, 1]), *s["skew"]))
        log("   quadrature check (every second node): max |change of mean| = %.1e sd, max |change of sd| = %.1e sd" % g["sub_check"])
        res[T] = g
    return res


def solver_check_on_posterior(post, res):
    """Change of the log posterior when the forward solver is refined (h/2, dt/2) or replaced by the independent
    reference, at nodes inside the 99.9 percent region of each window."""
    for T, g in res.items():
        nt = g["nt"]
        rng = np.random.default_rng(3)
        k = np.where(g["w"] >= hpd_threshold(g["w"], 0.999))[0]
        pick = rng.choice(k, size=min(30, len(k)), replace=False)
        th = g["th"][pick]
        lp0 = g["lpost"][pick]
        fine = lambda t_, n_: np.concatenate([solve(np.exp(t_[i:i + 1, 0]), np.exp(t_[i:i + 1, 1]), TOBS[:n_], SENS, h=H / 2, dt=DT / 2)
                                              for i in range(len(t_))])
        lp1 = post.logpost(th, nt, solver=fine)
        sub = pick[:8]
        refs = lambda t_, n_: np.stack([reference(np.exp(a), np.exp(b), TOBS[:n_], SENS)[0] for a, b in t_])
        lp2 = post.logpost(g["th"][sub], nt, solver=refs)
        log("CHECK window T=%g: change of log posterior with h/2, dt/2 over 30 nodes of the 99.9%% region: max %.3f (the log posterior varies "
            "by %.1f over that region); against the independent reference over 8 nodes: max %.3f" %
            (T, np.abs(lp1 - lp0).max(), lp0.max() - lp0.min(), np.abs(lp2 - g["lpost"][sub]).max()))


# ==================== linearized analysis as a function of the window
def fisher_curves(truth, lx, xs, tobs, dt=DT, Ts=None, eps=1e-4, solver_h=H, prior=True):
    D, r = truth
    pts = [(D, r), (D * np.exp(eps), r), (D * np.exp(-eps), r), (D, r * np.exp(eps)), (D, r * np.exp(-eps))]
    g = solve([p[0] for p in pts], [p[1] for p in pts], tobs, xs, lx=lx, dt=dt, h=solver_h)
    JD = (g[1] - g[2]) / (2 * eps); Jr = (g[3] - g[4]) / (2 * eps)
    out = []
    for T in Ts:
        nt = int(round(T / DTOBS))
        A = np.array([[np.sum(JD[:nt] ** 2), np.sum(JD[:nt] * Jr[:nt])], [np.sum(JD[:nt] * Jr[:nt]), np.sum(Jr[:nt] ** 2)]]) / DELTA ** 2
        C = np.linalg.inv(A + (np.diag(1 / PSD ** 2) if prior else 1e-10 * np.eye(2)))
        s = axes_summary(C)
        s["T"] = T
        out.append(s)
    return out


