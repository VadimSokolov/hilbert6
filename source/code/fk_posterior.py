"""Posterior of the Fisher Kolmogorov parameters (D, r), computed exactly on a grid.

Model: u_t = D u_xx + r u (1 - u) on [0, LX] with Neumann ends, u(0, x) = (1/2) erfc((x - X0)/(sqrt(2) S0)),
data u(t_j, x_i) + N(0, DELTA^2) on a grid of space time points, log normal priors for (D, r).
The posterior of (log D, log r) is evaluated on a two dimensional grid (no Markov chain), once for each of three
nested observation windows [0, T].  Everything quoted in the text of Chapter 12 is printed by this script.
The data are generated by an independent finite difference solver, the posterior uses a cosine transform solver.

Run: python3 fk_posterior.py          (about 10 minutes on a laptop; at most 3 threads)
     python3 fk_posterior.py --quick  (coarse grids and fewer repetitions, a few minutes, for testing)
     python3 fk_posterior.py --no-generator   (skip the generator study, about 3 minutes)
Output: ../figures/fk_posterior.pdf (override the folder with the environment variable FK_OUT; with FK_CACHE=file.pkl the
results are also saved, and --replot file.pkl redraws the figure from them in a second).
"""
